--PROJECT: MediTrack
--Purpose: Hospital Appointment and Waiting-Time Analysis

--SECTION 1: DISPLAY ALL APPOINTMENTS
SELECT * 
FROM APPOINTMENTS;

--SECTION 2: APPOINTMENT STATUS SUMMARY
--PURPOSE: Count the number of appointments belonging to each status.
--WHY: Helps the hospital understand how many appointments are completed, cancelled, scheduled, or marked as no-show.
SELECT STATUS,COUNT(*) "APPOINTMENT COUNT"
FROM APPOINTMENTS
GROUP BY STATUS;

--SECTION 3: Patient Waiting-Time Analysis
--WHY: Helps the hospital identify appointment delays and understand patient waiting time.
SELECT APPOINTMENT_ID,TO_CHAR(SCHEDULED_TIME,'HH24:MI') "SCHEDULED TIME",TO_CHAR(ACTUAL_START_TIME,'HH24:MI') "ACTUAL START TIME", (ACTUAL_START_TIME-SCHEDULED_TIME)*1440 "WAITING TIME"
FROM APPOINTMENTS
WHERE STATUS='COMPLETED';

--SECTION 4: AVERAGE PATIENT WAITING TIME
--WHY: Helps the hospital measure the average delay experienced by patients.
SELECT AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440) " AVG WAITING TIME"
FROM APPOINTMENTS
WHERE STATUS='COMPLETED';

--SECTION 5: APPOINTMENT COUNT BY DOCTOR
--WHY: Helps the hospital understand the workload of individual doctors.
SELECT A.DOCTOR_ID,D.DOCTOR_NAME, COUNT(A.DOCTOR_ID) "APPOINTMENT COUNT"
FROM DOCTORS D INNER JOIN APPOINTMENTS A
ON D.DOCTOR_ID=A.DOCTOR_ID
GROUP BY A.DOCTOR_ID,D.DOCTOR_NAME;

--SECTION 6: AVERAGE WAITING TIME BY DOCTOR
--WHY: Helps identify doctors whose appointments experience longer waiting times.
SELECT D.DOCTOR_ID, D.DOCTOR_NAME, AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440) "WAITING TIME"
FROM DOCTORS D INNER JOIN APPOINTMENTS A 
ON D.DOCTOR_ID=A.DOCTOR_ID AND STATUS='COMPLETED'
GROUP BY D.DOCTOR_ID,D.DOCTOR_NAME,A.DOCTOR_ID;

--SECTION 7: AVERAGE WAITING TIME BY DEPARTMENT
--WHY: Helps compare waiting times across different departments.
SELECT DE.DEPT_NAME,AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440) "AVG WAITING TIME"
FROM DOCTORS D INNER JOIN APPOINTMENTS A
ON D.DOCTOR_ID=A.DOCTOR_ID
INNER JOIN DEPARTMENTS DE
ON D.DEPT_ID=DE.DEPT_ID
AND STATUS='COMPLETED'
GROUP BY D.DEPT_ID,DE.DEPT_NAME
ORDER BY AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440);

--SECTION 8: DOCTORS WITHOUT COMPLETED APPOINTMENTS
--WHY: Helps the hospital review cancellations, no-shows, and pending appointments.
SELECT D.DOCTOR_NAME
FROM DOCTORS D INNER JOIN APPOINTMENTS A
ON D.DOCTOR_ID=A.DOCTOR_ID AND STATUS NOT IN('COMPLETED');

--SECTION 9: PATIENTS WITHOUT COMPLETED APPOINTMENTS
--WHY: Helps the hospital identify patients with cancelled, missed, or pending visits.
SELECT P.PATIENT_ID,P.PATIENT_NAME
FROM PATIENTS P INNER JOIN APPOINTMENTS A
ON P.PATIENT_ID=A.PATIENT_ID AND STATUS NOT IN('COMPLETED');

--SECTION 10: DOCTOR WITH THE LONGEST WAITING TIME
--WHY: Helps the hospital identify where delays may need further investigation.
SELECT * FROM ( 
SELECT D.DOCTOR_NAME,AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440) "AVG WAITING TIME"
FROM DOCTORS D INNER JOIN APPOINTMENTS A
ON D.DOCTOR_ID=A.DOCTOR_ID AND STATUS='COMPLETED'
GROUP BY D.DOCTOR_NAME, A.DOCTOR_ID
ORDER BY AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440) DESC
)
WHERE ROWNUM=1;

--SECTION 11: TOP 2 DOCTORS BY WAITING TIME
--WHY: Helps the hospital prioritize areas where waiting-time improvements may help.
SELECT * FROM ( 
SELECT D.DOCTOR_NAME,AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440) "AVG WAITING TIME"
FROM DOCTORS D INNER JOIN APPOINTMENTS A
ON D.DOCTOR_ID=A.DOCTOR_ID AND STATUS='COMPLETED'
GROUP BY D.DOCTOR_NAME, A.DOCTOR_ID
ORDER BY AVG((ACTUAL_START_TIME-SCHEDULED_TIME)*1440) DESC
)
WHERE ROWNUM<=2;

--SECTION 12: APPOINTMENT COUNT BY PATIENT
--WHY: Helps the hospital understand patient visit frequency and appointment history
SELECT P.PATIENT_ID, P.PATIENT_NAME, COUNT(A.PATIENT_ID) "TOTAL APPOINTMENTS"
FROM PATIENTS P LEFT OUTER JOIN APPOINTMENTS A
ON P.PATIENT_ID=A.PATIENT_ID
GROUP BY P.PATIENT_ID,P.PATIENT_NAME;

--SECTION 13: CREATE VIEW FOR WAITING TIME ANALYSIS
CREATE VIEW WAITING_TIME_VIEW AS
SELECT APPOINTMENT_ID,TO_CHAR(SCHEDULED_TIME,'HH24:MI') "SCHEDULED TIME",TO_CHAR(ACTUAL_START_TIME,'HH24:MI') "ACTUAL START TIME", (ACTUAL_START_TIME-SCHEDULED_TIME)*1440 "WAITING TIME"
FROM APPOINTMENTS
WHERE STATUS='COMPLETED';
--WAITING_TIME_VIEW
SELECT * FROM WAITING_TIME_VIEW;

--SECTION 15: COMBINED HOSPITAL APPOINTMENT VIEW
CREATE VIEW APPOINTMENT_DETAILS_VIEW AS
SELECT P.PATIENT_NAME,D.DOCTOR_NAME,DE.DEPT_NAME,A.SCHEDULED_TIME,A.ACTUAL_START_TIME,A.STATUS,(A.ACTUAL_START_TIME-A.SCHEDULED_TIME)*1440 "WAITING TIME"
FROM PATIENTS P INNER JOIN APPOINTMENTS A
ON P.PATIENT_ID=A.PATIENT_ID
INNER JOIN DOCTORS D
ON A.DOCTOR_ID=D.DOCTOR_ID
INNER JOIN DEPARTMENTS DE
ON DE.DEPT_ID=D.DEPT_ID;
--APPOINTMENT_DETAILS-VIEW
SELECT * FROM APPOINTMENT_DETAILS_VIEW;

--SECTION 16: DEPARTMENT-WISE APPOINTMENT SUMMARY
CREATE VIEW DEPARTMENT_APPOINTMENT_SUMMARY AS
SELECT DE.DEPT_NAME,COUNT(A.APPOINTMENT_ID) "TOTAL APPOINTMENTS",
SUM(CASE WHEN STATUS='COMPLETED' THEN 1 ELSE 0 END) AS COMPLETED,
SUM(CASE WHEN STATUS='CANCELLED' THEN 1 ELSE 0 END) AS CANCELLED,
SUM(CASE WHEN STATUS='SCHEDULED' THEN 1 ELSE 0 END) AS SCHEDULED,
SUM(CASE WHEN STATUS='NO-SHOW' THEN 1 ELSE 0 END) AS NO_SHOW
FROM DEPARTMENTS DE INNER JOIN DOCTORS D
ON DE.DEPT_ID=D.DEPT_ID
INNER JOIN APPOINTMENTS A
ON D.DOCTOR_ID=A.DOCTOR_ID
GROUP BY DE.DEPT_NAME;
--DEPARTMENT_APPOINTMENT_SUMMARY_VIEW
SELECT *
FROM DEPARTMENT_APPOINTMENT_SUMMARY;

--PL/SQL

CREATE OR REPLACE PROCEDURE DISPLAY_PATIENT
(P_ID IN NUMBER)
AS
    V_NAME PATIENTS.PATIENT_NAME%TYPE;
    V_AGE  PATIENTS.AGE%TYPE;
BEGIN
    SELECT PATIENT_NAME, AGE
    INTO V_NAME, V_AGE
    FROM PATIENTS
    WHERE PATIENT_ID = P_ID;

    DBMS_OUTPUT.PUT_LINE('Patient ID: ' || P_ID);
    DBMS_OUTPUT.PUT_LINE('Patient Name: ' || V_NAME);
    DBMS_OUTPUT.PUT_LINE('Age: ' || V_AGE);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Patient not found.');
END;
/
EXEC DISPLAY_PATIENT(1);
/
SET SERVEROUTPUT ON;

